
-- Database, schemas, warehouse
CREATE DATABASE IF NOT EXISTS NEWS_PIPELINE;
CREATE SCHEMA IF NOT EXISTS NEWS_PIPELINE.RAW;
CREATE SCHEMA IF NOT EXISTS NEWS_PIPELINE.STAGING;
CREATE SCHEMA IF NOT EXISTS NEWS_PIPELINE.ANALYTICS;

CREATE WAREHOUSE IF NOT EXISTS NEWS_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

-- Pipeline role and service user (key-pair login)
CREATE ROLE IF NOT EXISTS PIPELINE_ROLE;
GRANT USAGE ON WAREHOUSE NEWS_WH TO ROLE PIPELINE_ROLE;
GRANT USAGE ON DATABASE NEWS_PIPELINE TO ROLE PIPELINE_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE NEWS_PIPELINE TO ROLE PIPELINE_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA NEWS_PIPELINE.STAGING TO ROLE PIPELINE_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA NEWS_PIPELINE.ANALYTICS TO ROLE PIPELINE_ROLE;

CREATE USER IF NOT EXISTS DAGSTER_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = PIPELINE_ROLE
  DEFAULT_WAREHOUSE = NEWS_WH
  RSA_PUBLIC_KEY = '<public key printed by scripts/make_keys.py>';
GRANT ROLE PIPELINE_ROLE TO USER DAGSTER_SVC;

-- Connection from Snowflake to the S3 bucket
CREATE STORAGE INTEGRATION IF NOT EXISTS <integration_name>
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = '<arn of the IAM role Snowflake assumes>'
  STORAGE_ALLOWED_LOCATIONS = ('s3://<bucket>/raw/');

-- File formats
CREATE FILE FORMAT IF NOT EXISTS NEWS_PIPELINE.RAW.CSV_GZ_FORMAT
  TYPE = CSV
  COMPRESSION = GZIP
  PARSE_HEADER = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

CREATE FILE FORMAT IF NOT EXISTS NEWS_PIPELINE.RAW.CSV_FORMAT
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

-- Stages
CREATE STAGE IF NOT EXISTS NEWS_PIPELINE.RAW.MASSIVE_STAGE
  URL = 's3://<bucket>/raw/massive/'
  STORAGE_INTEGRATION = <integration_name>
  FILE_FORMAT = NEWS_PIPELINE.RAW.CSV_GZ_FORMAT;

CREATE STAGE IF NOT EXISTS NEWS_PIPELINE.RAW.DASH_EXPORTS_STAGE
  URL = 's3://<bucket>/raw/trading_dash/exports/'
  STORAGE_INTEGRATION = <integration_name>
  FILE_FORMAT = NEWS_PIPELINE.RAW.CSV_FORMAT;

-- Raw tables
CREATE TABLE IF NOT EXISTS NEWS_PIPELINE.RAW.RAW_DAY_AGGS (
    ticker        VARCHAR,
    volume        NUMBER,
    open          FLOAT,
    close         FLOAT,
    high          FLOAT,
    low           FLOAT,
    window_start  NUMBER,
    transactions  NUMBER,
    file_name     VARCHAR,
    loaded_at     TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS NEWS_PIPELINE.RAW.RAW_DASH_EXPORTS (
    time        VARCHAR,
    time_et     VARCHAR,
    feed        VARCHAR,
    source      VARCHAR,
    tickers     VARCHAR,
    headline    VARCHAR,
    news_type   VARCHAR,
    form_type   VARCHAR,
    file_name   VARCHAR,
    loaded_at   TIMESTAMP_LTZ
);

CREATE TABLE IF NOT EXISTS NEWS_PIPELINE.RAW.RAW_TICKER_DETAILS (
    ticker           VARCHAR,
    name             VARCHAR,
    type             VARCHAR,
    sic_code         VARCHAR,
    sic_description  VARCHAR,
    file_name        VARCHAR,
    loaded_at        TIMESTAMP_LTZ
);

-- Pipeline access to stages, formats, and raw tables
GRANT USAGE ON STAGE NEWS_PIPELINE.RAW.MASSIVE_STAGE TO ROLE PIPELINE_ROLE;
GRANT USAGE ON STAGE NEWS_PIPELINE.RAW.DASH_EXPORTS_STAGE TO ROLE PIPELINE_ROLE;
GRANT USAGE ON FILE FORMAT NEWS_PIPELINE.RAW.CSV_GZ_FORMAT TO ROLE PIPELINE_ROLE;
GRANT USAGE ON FILE FORMAT NEWS_PIPELINE.RAW.CSV_FORMAT TO ROLE PIPELINE_ROLE;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA NEWS_PIPELINE.RAW TO ROLE PIPELINE_ROLE;